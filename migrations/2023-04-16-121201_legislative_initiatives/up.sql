create table legislative_initiatives (
    -- use serial id -> add inr, and UNIQUE of (inr, ityp, gp)
    id serial primary key,
    ityp varchar(7) not null,
    doktyp varchar(20) not null,
    gp varchar(7) not null,
    inr int not null,
    emphasis varchar(16000),
    ai_emphasis varchar(16000),
    is_emphasis_ai_generated boolean not null default false,
    title text not null,
    pre_declined_type varchar(10),
    voted_by_name boolean not null default false,
    description text not null,
    accepted varchar(10),
    vote_date date,
    nr_plenary_activity_date date not null default now(),
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now(),
    raw_data_created_at timestamptz not null,
    raw_data_updated_at timestamptz,
    requires_simple_majority boolean not null default true,
    -- was_invisibly_declined boolean default false,
    plenary_session_id int,
    is_law boolean not null default false,
    law_accepted boolean,
    has_reference boolean default false,
    is_voteable_on boolean not null default false,
    is_urgent boolean not null default false,
    voting varchar(255),
    hash bigint,
    foreign key (plenary_session_id) references plenar_infos(id),
    UNIQUE (inr, ityp, gp)
);
